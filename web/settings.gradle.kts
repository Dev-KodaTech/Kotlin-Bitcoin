rootProject.name = "kotlin-bitcoins-web"

pluginManagement {
    repositories {
        gradlePluginPortal()
        google()
        mavenCentral()
    }
}

dependencyResolutionManagement {
    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
    repositories {
        google()
        mavenCentral()

        // Tool distributions downloaded by the Kotlin Gradle plugin for wasmJs (Node, Yarn, Binaryen).
        // Declared here because FAIL_ON_PROJECT_REPOS forbids the plugin from adding them to the projects;
        // web/build.gradle.kts clears the plugin's own download URLs (downloadBaseUrl).
        exclusiveContent {
            forRepository {
                ivy("https://nodejs.org/dist") {
                    name = "Node.js distributions"
                    patternLayout { artifact("v[revision]/[artifact](-v[revision]-[classifier]).[ext]") }
                    metadataSources { artifact() }
                }
            }
            filter { includeModule("org.nodejs", "node") }
        }
        exclusiveContent {
            forRepository {
                ivy("https://github.com/yarnpkg/yarn/releases/download") {
                    name = "Yarn distributions"
                    patternLayout { artifact("v[revision]/[artifact](-v[revision]).[ext]") }
                    metadataSources { artifact() }
                }
            }
            filter { includeModule("com.yarnpkg", "yarn") }
        }
        exclusiveContent {
            forRepository {
                ivy("https://github.com/WebAssembly/binaryen/releases/download") {
                    name = "Binaryen distributions"
                    patternLayout { artifact("version_[revision]/binaryen-version_[revision]-[classifier].[ext]") }
                    metadataSources { artifact() }
                }
            }
            filter { includeModule("com.github.webassembly", "binaryen") }
        }
    }
}

// The image build (web/Dockerfile) leaves e2e/ out of the context (.dockerignore), so only the modules present on
// disk are included.
listOf("core", "state", "data", "ui", "app", "e2e")
    .filter { file(it).isDirectory }
    .forEach { include(it) }
