// Consumer fixtures (W-12): web/contract-fixtures/** becomes ContractFixtures.kt for the commonTest of :data, so the
// wasm tests never read files at run time. The fixtures themselves are validated against the contract in the API build.
val contractFixturesDir: Directory = rootProject.layout.projectDirectory.dir("contract-fixtures")
val generatedFixturesRoot: Provider<Directory> =
    layout.buildDirectory.dir(
        "generated/contractFixtures/commonTest/kotlin",
    )

val generateContractFixtures by tasks.registering {
    group = "build"
    description = "Generates ContractFixtures.kt from web/contract-fixtures (manifest + JSON files)."
    val sourceDir = contractFixturesDir.asFile
    val outputRoot = generatedFixturesRoot
    inputs.dir(contractFixturesDir).withPathSensitivity(PathSensitivity.RELATIVE)
    outputs.dir(outputRoot)
    doLast {
        fun literal(text: String): String =
            buildString {
                append('"')
                text.forEach { char ->
                    when (char) {
                        '\\' -> append("\\\\")
                        '"' -> append("\\\"")
                        '$' -> append("\\$")
                        '\n' -> append("\\n")
                        '\r' -> append("\\r")
                        '\t' -> append("\\t")
                        else -> append(char)
                    }
                }
                append('"')
            }

        @Suppress("UNCHECKED_CAST")
        val manifest = JsonSlurper().parse(sourceDir.resolve("manifest.json")) as Map<String, Any?>

        @Suppress("UNCHECKED_CAST")
        val entries = manifest["fixtures"] as List<Map<String, Any?>>
        val files =
            sourceDir
                .walkTopDown()
                .filter { it.isFile && it.extension == "json" && it.name != "manifest.json" }
                .map { it.relativeTo(sourceDir).invariantSeparatorsPath to it.readText() }
                .sortedBy { it.first }
                .toList()
        val missing = entries.map { it["file"] as String }.filter { file -> files.none { it.first == file } }
        check(missing.isEmpty()) { "manifest.json cites missing fixtures: $missing" }

        val entryLines =
            entries.joinToString(",\n") { entry ->
                "            Entry(file = ${literal(
                    entry["file"] as String,
                )}, method = ${literal(entry["method"] as String)}, " +
                    "path = ${literal(entry["path"] as String)}, status = ${(entry["status"] as Number).toInt()}, " +
                    "scenario = ${literal(entry["scenario"] as String)})"
            }
        val fileLines = files.joinToString(",\n") { (path, text) -> "            ${literal(path)} to ${literal(text)}" }
        val source =
            """
            |// Generated by :data:generateContractFixtures from web/contract-fixtures. Do not edit.
            |package com.kotlinbitcoins.web.data.fixtures
            |
            |object ContractFixtures {
            |    data class Entry(
            |        val file: String,
            |        val method: String,
            |        val path: String,
            |        val status: Int,
            |        val scenario: String,
            |    )
            |
            |    data class Fixture(
            |        val entry: Entry,
            |        val body: String,
            |    )
            |
            |    val entries: List<Entry> =
            |        listOf(
            |$entryLines,
            |        )
            |
            |    private val files: Map<String, String> =
            |        mapOf(
            |$fileLines,
            |        )
            |
            |    /** Paths of every fixture file, relative to web/contract-fixtures (e.g. "problem/INVALID_AMOUNT.json"). */
            |    val paths: Set<String> get() = files.keys
            |
            |    fun byFile(path: String): String = files[path] ?: error("Unknown fixture file: " + path)
            |
            |    fun byScenario(name: String): Fixture {
            |        val entry = entries.firstOrNull { it.scenario == name } ?: error("Unknown fixture scenario: " + name)
            |        return Fixture(entry, byFile(entry.file))
            |    }
            |}
            |
            """.trimMargin()
        val target = outputRoot.get().file("com/kotlinbitcoins/web/data/fixtures/ContractFixtures.kt").asFile
        target.parentFile.mkdirs()
        target.writeText(source)
    }
}

